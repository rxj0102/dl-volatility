"""Render the README results blocks from outputs/.

    python scripts/render_readme.py          rewrite the blocks
    python scripts/render_readme.py --check  exit 1 if the README is stale

Inputs are written by `python -m training.run_all --skip-tft` (model_comparison.csv,
regime_performance.csv) and `python -m evaluation.seed_study 5` (lstm_seed_study.csv).
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
README = ROOT / "README.md"
OUT = ROOT / "outputs"
START = "<!-- results:start (generated by scripts/render_readme.py, do not edit by hand) -->"
END = "<!-- results:end -->"

NAMES = {"GARCH": "GJR-GARCH", "XGB": "XGBoost", "LSTM": "LSTM", "Random walk": "Random walk (squared return at t-1)",
         "22d mean": "22-day mean of squared returns"}


def block() -> str:
    mc = pd.read_csv(OUT / "model_comparison.csv")
    rp = pd.read_csv(OUT / "regime_performance.csv")
    lines = [
        START,
        "Test set scored on the dates where every model has a forecast. Positive DM statistics mean the model has "
        "higher QLIKE than GJR-GARCH (Diebold-Mariano, one-step).",
        "",
        "| Model | QLIKE | RMSE (log-vol) | DM vs GARCH | p-value |",
        "|---|---|---|---|---|",
    ]
    best = mc.QLIKE.idxmin()
    for i, r in mc.iterrows():
        name = NAMES.get(r.model, r.model)
        name = f"**{name}**" if i == best else name
        lines.append(f"| {name} | {r.QLIKE:.4f} | {r.RMSE:.4f} | {r.DM_vs_GARCH_stat:+.3f} | {r.DM_p_value:.3f} |")
    lines.append("| TFT | not run | not run | not run | not run |")
    learned = mc[mc.model.isin(["LSTM", "XGB"])]
    lines += [
        "",
        f"- Lowest QLIKE: {NAMES.get(mc.loc[best, 'model'])}. Smallest DM p-value against GJR-GARCH among the learned "
        f"models: {learned.DM_p_value.min():.3f}.",
        "",
        "Regime-conditional QLIKE (VIX below 20 against VIX above 25):",
        "",
        "| Model | Low-vol QLIKE | High-vol QLIKE |",
        "|---|---|---|",
    ]
    n_low, n_high = int(rp.n_low.iloc[0]), int(rp.n_high.iloc[0])
    for r in rp.itertuples():
        lines.append(f"| {NAMES.get(r.model, r.model)} | {r.low_vol_QLIKE:.4f} | {r.high_vol_QLIKE:.4f} |")
    lines.append(f"\n{n_low} low-vol and {n_high} high-vol test days.")
    seed_path = OUT / "lstm_seed_study.csv"
    if seed_path.exists():
        ss = pd.read_csv(seed_path)
        lstm = ss[ss.iloc[:, 0].astype(str).str.startswith("LSTM seed")]
        qcol = "QLIKE" if "QLIKE" in ss.columns else ss.columns[1]
        g = ss[ss.iloc[:, 0].astype(str).str.contains("GARCH")]
        line = (f"\nLSTM seed study ({len(lstm)} seeds, same dates): QLIKE {lstm[qcol].min():.4f} to "
                f"{lstm[qcol].max():.4f}, median {lstm[qcol].median():.4f}")
        if len(g):
            line += f"; GJR-GARCH {g[qcol].iloc[0]:.4f}, beaten by {int((lstm[qcol] < g[qcol].iloc[0]).sum())} of {len(lstm)} seeds"
        lines.append(line + ".")
    lines.append(END)
    return "\n".join(lines)


def main() -> int:
    text = README.read_text()
    pat = re.compile(re.escape(START) + r".*?" + re.escape(END), re.S)
    if not pat.search(text):
        print("results markers not found in README.md", file=sys.stderr)
        return 1
    new = pat.sub(lambda _: block(), text)
    if "--check" in sys.argv:
        if new != text:
            print("README results block is stale: rerun the pipeline and render", file=sys.stderr)
            return 1
        print("README results block matches outputs/")
        return 0
    README.write_text(new)
    return 0


if __name__ == "__main__":
    sys.exit(main())
